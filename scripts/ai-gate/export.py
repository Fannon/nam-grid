"""Write a trained checkpoint as NeuralAmpModeler/AIGateModel.h.

Usage: export.py <model.pt> [--binary weights.bin] [--bias <logit offset>]
The optional binary (int32 inner, hidden, tick rate; then float32 weights) feeds experiment
tools. --bias is added to the output biases, so the plugin's Sensitivity 0 can sit at a
chosen operating point without retraining.
"""
import argparse
from pathlib import Path

import numpy as np
import torch

FIELDS = [("inputWeight", "inp.weight"), ("inputBias", "inp.bias"), ("gruInput", "gru.weight_ih_l0"),
          ("gruHidden", "gru.weight_hh_l0"), ("gruInputBias", "gru.bias_ih_l0"), ("gruHiddenBias", "gru.bias_hh_l0"),
          ("outputWeight", "out.weight"), ("outputBias", "out.bias")]


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("checkpoint")
    parser.add_argument("--binary")
    parser.add_argument("--bias", type=float, default=0.0)
    parser.add_argument("--header", default=str(Path(__file__).resolve().parents[2] / "NeuralAmpModeler" / "AIGateModel.h"))
    args = parser.parse_args()
    checkpoint = torch.load(args.checkpoint, map_location="cpu", weights_only=False)
    state, options = checkpoint["model"], checkpoint["args"]
    arrays = {name: state[key].numpy().astype(np.float32).ravel().copy() for name, key in FIELDS}
    arrays["outputBias"] += np.float32(args.bias)
    sizes = [options["inner"], options["hidden"], 48000 // options.get("hop", 32)]
    if args.binary:
        with open(args.binary, "wb") as f:
            f.write(np.array(sizes, np.int32).tobytes())
            for name, _ in FIELDS:
                f.write(arrays[name].tobytes())
    lines = ["// Generated by scripts/ai-gate/export.py from a trained checkpoint; do not edit by hand.",
             "// Training data and attribution: docs/module-implementation.md and ThirdPartyNotices.txt.",
             "#pragma once", "", "namespace ai_gate::model", "{",
             f"inline constexpr int inner = {sizes[0]}, hidden = {sizes[1]}, tickRate = {sizes[2]};"]
    for name, _ in FIELDS:
        values = arrays[name]
        lines.append(f"inline constexpr float {name}[{len(values)}] = {{")
        for start in range(0, len(values), 8):
            lines.append("  " + ", ".join(f"{v:.9g}f" if "." in f"{v:.9g}" or "e" in f"{v:.9g}" else f"{v:.9g}.f"
                                          for v in values[start : start + 8]) + ",")
        lines.append("};")
    lines += ["} // namespace ai_gate::model", ""]
    Path(args.header).write_text("\n".join(lines), encoding="utf-8", newline="\n")
    print(sum(len(v) for v in arrays.values()), "weights ->", args.header)


if __name__ == "__main__":
    main()
