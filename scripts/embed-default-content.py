#!/usr/bin/env python3
"""Embed factory files as zlib streams; the capture retains its original bytes."""
import argparse
import json
from pathlib import Path
import zlib


def generate(capture: bytes, preset: bytes) -> str:
    # Only the rig JSON is minified. Capture bytes/hashes must remain unchanged.
    preset = json.dumps(json.loads(preset), ensure_ascii=False, separators=(",", ":")).encode("utf-8")
    source = '''// Generated by scripts/embed-default-content.py; do not edit.
#include "DefaultContent.h"
#include "stb_image.h"
#include <stdexcept>

namespace default_content
{
// Reuse NanoVG's existing decoder; no additional runtime library is required.
static std::vector<unsigned char> Decode(const unsigned char* data, int size, int originalSize)
{
  std::vector<unsigned char> result(originalSize);
  if (stbi_zlib_decode_buffer(reinterpret_cast<char*>(result.data()), originalSize,
                             reinterpret_cast<const char*>(data), size) != originalSize)
    throw std::runtime_error("Invalid embedded factory content");
  return result;
}
'''
    for name, data in (("CleanCapture", capture), ("CleanPreset", preset)):
        compressed = zlib.compress(data, level=9)
        source += f"static const unsigned char {name}Data[] = {{\n"
        for offset in range(0, len(compressed), 32):
            source += "  " + "".join(f"0x{byte:02x}," for byte in compressed[offset:offset + 32]) + "\n"
        source += f'''}};
std::vector<unsigned char> {name}()
{{
  return Decode({name}Data, sizeof({name}Data), {len(data)});
}}
'''
    return source + "} // namespace default_content\n"


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--capture", type=Path, required=True)
    parser.add_argument("--preset", type=Path, required=True)
    parser.add_argument("--output", type=Path, required=True)
    args = parser.parse_args()
    source = generate(args.capture.read_bytes(), args.preset.read_bytes())
    args.output.parent.mkdir(parents=True, exist_ok=True)
    if not args.output.exists() or args.output.read_text(encoding="utf-8") != source:
        args.output.write_text(source, encoding="utf-8")


if __name__ == "__main__":
    main()
